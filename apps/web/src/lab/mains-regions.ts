/** Approximate Fuji River cut. East is mostly 50 Hz, west mostly 60 Hz. */
export const JAPAN_CUT_LON = 138.6
export const JAPAN_EDGE_DEG = 0.45

export function japanSide(lon: number): 50 | 60 | 'edge' {
  if (Math.abs(lon - JAPAN_CUT_LON) <= JAPAN_EDGE_DEG) return 'edge'
  return lon > JAPAN_CUT_LON ? 50 : 60
}

